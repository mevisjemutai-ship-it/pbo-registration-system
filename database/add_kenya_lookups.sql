-- ---------------------------------------------------------------
-- Kenya location lookups for the PBO portal.
--
-- Reference data only. Nothing in application_addresses or
-- application_operating_locations changes: those keep storing the
-- county / sub-county NAME exactly as they do today. These tables
-- exist to power type-ahead suggestions and the review-step warning.
--
--   mysql -u root -p pbo_portal < database/add_kenya_lookups.sql
--
-- Safe to re-run: it drops and reloads only these three tables.
-- ---------------------------------------------------------------

USE pbo_portal;

SET NAMES utf8mb4;

START TRANSACTION;

DROP TABLE IF EXISTS kenya_postal_codes;
DROP TABLE IF EXISTS kenya_sub_counties;
DROP TABLE IF EXISTS kenya_counties;

CREATE TABLE kenya_counties (
    county_code     TINYINT UNSIGNED NOT NULL,
    county_name     VARCHAR(100) NOT NULL,
    capital         VARCHAR(60)  NULL,
    PRIMARY KEY (county_code),
    UNIQUE KEY uq_kenya_county_name (county_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE kenya_sub_counties (
    id              SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT,
    county_code     TINYINT UNSIGNED NOT NULL,
    sub_county_name VARCHAR(100) NOT NULL,
    ward_count      TINYINT UNSIGNED NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_kenya_sub_county (county_code, sub_county_name),
    CONSTRAINT fk_kenya_sub_county_county FOREIGN KEY (county_code)
        REFERENCES kenya_counties (county_code) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE kenya_postal_codes (
    postal_code     CHAR(5) NOT NULL,
    post_office     VARCHAR(100) NOT NULL,
    county_code     TINYINT UNSIGNED NULL,
    -- 0 = the county on this row came from a third-party list and is
    --     sometimes wrong, so it must never auto-fill the county field.
    county_verified TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (postal_code),
    KEY idx_kenya_postal_county (county_code),
    KEY idx_kenya_post_office (post_office),
    CONSTRAINT fk_kenya_postal_county FOREIGN KEY (county_code)
        REFERENCES kenya_counties (county_code) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

